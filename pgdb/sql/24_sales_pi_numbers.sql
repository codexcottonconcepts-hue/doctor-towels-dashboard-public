-- Automatic PI numbers for new web entries. Invoice numbers remain optional
-- and are never generated. Existing PI/invoice strings and ledger rows stay
-- unchanged, including genuine shared PIs across brands and product lines.
begin;
create table if not exists txn.sales_pi_counter (
    fy smallint primary key references master.financial_year(fy) on delete restrict,
    last_number bigint not null default 0 check(last_number>=0),
    updated_at timestamptz not null default clock_timestamp()
);
grant select,insert,update on txn.sales_pi_counter to dstt_app;
comment on table txn.sales_pi_counter is 'Transactional global-per-financial-year web PI counter. Existing PI suffixes, including deleted history and A/B variants, are consulted before allocation.';
comment on column txn.sales_entry.pi_number is 'Existing PI identity is preserved; new web entries receive DST-PI{FY2}-{NNN} automatically on commit.';
comment on column txn.sales_entry.invoice_no is 'Optional entered billing invoice number. Never generated by the sales-entry application.';
commit;
